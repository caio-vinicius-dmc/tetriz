CREATE TABLE IF NOT EXISTS tetriz_records (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 name VARCHAR(24) NOT NULL,
 avatar TINYINT UNSIGNED NOT NULL DEFAULT 0,
 photo MEDIUMBLOB NULL,
 score INT UNSIGNED NOT NULL,
 `lines` INT UNSIGNED NOT NULL,
 level INT UNSIGNED NOT NULL,
 duration INT UNSIGNED NOT NULL,
 rules SMALLINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX ranking (rules, score DESC, created_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tetriz_rate_limits (
 bucket CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 hits INT UNSIGNED NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL,
 INDEX expiry (expires_at)
) ENGINE=InnoDB;
